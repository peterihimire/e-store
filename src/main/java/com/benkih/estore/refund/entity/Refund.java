package com.benkih.estore.refund.entity;

import com.benkih.estore.common.entity.AuditableEntity;
import com.benkih.estore.common.enums.CurrencyCode;
import com.benkih.estore.common.enums.PaymentProvider;
import com.benkih.estore.common.enums.RefundGatewayStatus;
import com.benkih.estore.common.enums.RefundStatus;
import com.benkih.estore.payment.entity.Payment;
import com.benkih.estore.user.entity.User;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "refunds")
public class Refund extends AuditableEntity {

    //  @Column(nullable = false, unique = true, updatable = false)
    //  private String slug = UUID.randomUUID().toString();

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "payment_id", nullable = false)
    private Payment payment;

    @Column(nullable = false, precision = 19, scale = 2)
    private BigDecimal amount;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private CurrencyCode currency;

    @Enumerated(EnumType.STRING)
    @Column(name = "refund_status", nullable = false)
    private RefundStatus refundStatus = RefundStatus.REQUESTED;

    @Enumerated(EnumType.STRING)
    @Column(name = "gateway_status", nullable = false)
    private RefundGatewayStatus gatewayStatus = RefundGatewayStatus.PENDING;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private PaymentProvider provider;

    /** Refund reference generated by your system. */
    @Column(nullable = false, unique = true)
    private String reference;

    /** Refund identifier returned by Paystack/Stripe/etc. */
    @Column(unique = true)
    private String gatewayRefundId;

    /** Human-readable reason. */
    @Column(length = 1000)
    private String reason;

    /** Raw response from payment gateway. */
    @Column(length = 4000)
    private String gatewayResponse;

    /** Failure message if refund fails. */
    @Column(length = 1000)
    private String failureReason;

    /** Only needed when refunding to another account. Leave null for normal gateway refunds. */
    private String bankCode;

    private String accountNumber;
    private String accountName;

    private Instant refundedAt;

    @OneToMany(mappedBy = "refund", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<RefundItem> items = new ArrayList<>();

    public void addItem(RefundItem item) {
        items.add(item);
        item.setRefund(this);
    }
}
